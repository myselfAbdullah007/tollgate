import {createRequire} from 'node:module';
import {writeFile} from 'node:fs/promises';
const require = createRequire(import.meta.url);
const {chromium} = require('../apps/dashboard/node_modules/playwright');
const browser = await chromium.launch(process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE ? {executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE} : {});
const page = await browser.newPage({viewport:{width:1440,height:1000}});
const base=process.env.PLAYWRIGHT_BASE_URL||'http://127.0.0.1:3187';
await page.goto(base+'/login');
await page.getByRole('button',{name:'Use demo credentials'}).click();
await page.getByRole('button',{name:'Sign in to workspace'}).click();
await page.getByRole('heading',{name:'Overview',exact:true}).waitFor();
await page.getByText('Connecting to your workspace…').waitFor({state:'hidden'});
const observations={};
let injected,submitted;
await page.route('**/api/admin/v1/tenants/default/plans',async route=>{
 const response=await route.fetch(), rows=await response.json();
 const plan=rows.find(p=>p.name==='Pro');
 plan.pii_block_categories=['CARD','EMAIL','SECRET'];
 plan.degradation=[{at:.6,tier:1},{at:.8,tier:2},{at:.95,tier:3}];
 injected=structuredClone(plan);
 await route.fulfill({response,json:rows});
});
await page.route('**/api/admin/v1/tenants/default/plans/*',async route=>{
 if(route.request().method()==='PATCH'){
  submitted=route.request().postDataJSON();
  await route.fulfill({status:200,contentType:'application/json',body:JSON.stringify({...injected,...submitted})});
 }else await route.continue();
});
await page.goto(base+'/plans');
await page.getByText('Connecting to your workspace…').waitFor({state:'hidden'});
await page.locator('.plan-card').filter({has:page.getByRole('heading',{name:'Pro',exact:true})}).getByRole('button',{name:'Edit plan'}).click();
await page.getByRole('dialog').getByRole('button',{name:'Save changes'}).click();
await page.getByRole('dialog').waitFor({state:'hidden'});
observations.plan_editor_roundtrip={originalCategories:injected.pii_block_categories,submittedCategories:submitted.pii_block_categories,originalThresholds:injected.degradation,submittedThresholds:submitted.degradation,productionWrites:'None; PATCH intercepted and fulfilled with fixture response'};
await page.unrouteAll({behavior:'wait'});
const urls=[];
page.on('request',r=>{if(r.url().includes('/tenants/default/logs?'))urls.push(r.url());});
await page.goto(base+'/logs');
await page.getByText('Connecting to your workspace…').waitFor({state:'hidden'});
await page.getByRole('combobox',{name:'Date range'}).selectOption('7');
await page.waitForResponse(r=>r.url().includes('/tenants/default/logs?'));
observations.log_date_range={requestUrls:urls,range:'Last 7 days',dateParameterSent:urls.at(-1).includes('days=')};
const customers=await (await page.request.get(base+'/api/admin/v1/tenants/default/customers')).json();
await page.goto(base+'/customers/'+customers[0].id);
await page.getByText('Connecting to your workspace…').waitFor({state:'hidden'});
observations.customer_log_navigation={customer:customers[0].name,href:await page.getByRole('link',{name:'Open request logs'}).getAttribute('href'),expected:'Customer-specific query preserved'};
await page.route('**/api/admin/v1/tenants',async route=>{
 const response=await route.fetch(),rows=await response.json();
 rows.push({id:'audit-workspace-id',name:'audit-workspace',display_name:'Audit second workspace',rpm:321,default_plan:'Free'});
 await route.fulfill({response,json:rows});
});
await page.route('**/api/admin/v1/tenants/audit-workspace/**',async route=>{
 if(route.request().method()!=='GET')throw new Error('Audit must not write workspace settings');
 const response=await route.fetch({url:route.request().url().replace('/tenants/audit-workspace/','/tenants/default/')});
 await route.fulfill({response});
});
await page.goto(base+'/settings');
await page.getByText('Connecting to your workspace…').waitFor({state:'hidden'});
const before=await page.getByRole('textbox',{name:'Workspace name',exact:true}).inputValue();
await page.locator('.workspace-switch').click();
await page.locator('.workspace-menu').getByRole('button',{name:'Audit second workspace'}).click();
await page.waitForResponse(r=>r.url().includes('/tenants/audit-workspace/usage'));
await page.locator('.workspace-switch').filter({hasText:'Audit second workspace'}).waitFor();
observations.workspace_settings_state={before,selectedWorkspace:'Audit second workspace',displayNameInput:await page.getByRole('textbox',{name:'Workspace name',exact:true}).inputValue(),expected:'Input reinitializes for the newly selected workspace',productionWrites:'None; workspace supplied with intercepted GET fixtures'};
await page.unrouteAll({behavior:'wait'});
await page.setViewportSize({width:390,height:844});
await page.getByRole('button',{name:'Open navigation'}).click();
observations.mobile_sidebar=await page.evaluate(()=>{const e=document.querySelector('button[aria-label="Sign out"]');return {signOutBottom:e.getBoundingClientRect().bottom,viewportHeight:innerHeight,sidebarOverflow:getComputedStyle(document.querySelector('.sidebar')).overflowY};});
await page.screenshot({path:'docs/audits/2026-10-28/mobile-sidebar-open.png'});
await writeFile('docs/audits/2026-10-28/workflow-probes.json',JSON.stringify(observations,null,2)+'\n');
console.log(JSON.stringify(observations,null,2));
await browser.close();
